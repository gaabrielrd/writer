it.each([1, 2, 3, 4, 5, 6])(
  'reads JSON v%i actually generated by exportManuscript, keeping unknown legacy availability explicit',
  async (version) => {
    const book: Book = {
      ...exportBook,
      coverUrl: 'https://example.invalid/cover?token=PRIVATE_TOKEN',
      ...(version >= 2 ? { universeId: 'world' } : {}),
      ...(version >= 3 ? { personaId: DEFAULT_PERSONAS[0]!.id } : {}),
      ...(version >= 5 ? { hasSceneResources: true, sceneRevision: 9 } : {}),
      ...(version === 6 ? { hasNarrativeResources: true, narrativeRevision: 8 } : {}),
    };
    const chapter: Chapter = {
      ...exportChapter,
      content: '',
      ...(version >= 4 ? { actId: 'act' } : {}),
      ...(version >= 5 ? { contentMode: 'scenes', assemblyRevision: 1, structureRevision: 1 } : {}),
    };
    vi.mocked(getBook).mockResolvedValue(book);
    vi.mocked(listChapters).mockResolvedValue([chapter]);
    if (version >= 4)
      vi.mocked(listActs).mockResolvedValue([
        { id: 'act', name: null, order: 1, createdAt: 1, updatedAt: 2 },
      ]);
    if (version >= 5) {
      const content = '\ufeffCanonical scene 🌙';
      vi.mocked(captureSceneBookBackup).mockResolvedValue({
        schemaVersion: 1,
        projectRevision: 9,
        groups: [
          {
            id: chapter.id,
            title: chapter.title,
            kind: 'chapter',
            contentMode: 'scenes',
            assemblyRevision: 1,
            structureRevision: 1,
            wordCount: 3,
            sceneCount: 1,
            rankSlot: 'B',
            order: 1,
            actId: 'act',
            updatedAt: 2,
          },
        ],
        scenes: [
          {
            id: 'scene',
            schemaVersion: 1,
            revision: 1,
            title: 'Scene',
            parentId: chapter.id,
            stage: 'planned',
            archived: false,
            rank: 'V',
            wordCount: 3,
            bodyHash: createHash('sha256').update(content).digest('hex'),
            bodyBytes: Buffer.byteLength(content),
            createdAt: 1,
            updatedAt: 2,
            content,
            planning: { objective: '', conflict: '', pointOfView: '' },
            references: [
              {
                id: 'reference',
                reference: { kind: 'universe', scopeId: 'world', entityId: 'global' },
                available: false,
                name: 'PRIVATE RESOLVED NAME',
              },
            ],
          },
        ],
        sources: [
          {
            id: chapter.id,
            content: 'Original source',
            hash: createHash('sha256').update('Original source').digest('hex'),
            original: {
              title: 'Original',
              order: 1,
              personaComplement: { personaId: 'missing-source-style', overrides: [] },
            },
          },
        ],
      });
    }
    if (version === 6) {
      const base = {
        schemaVersion: 1 as const,
        revision: 1,
        title: 'Arc',
        rank: 'V',
        createdAt: 1,
        updatedAt: 2,
        references: [],
      };
      vi.mocked(captureNarrativeBookBackup).mockResolvedValue({
        schemaVersion: 1,
        projectRevision: 8,
        sceneRevision: 9,
        arcs: [
          { ...base, id: 'arc', kind: 'arc', initialState: '', objective: '', plannedOutcome: '' },
        ],
        milestones: [],
        events: [
          {
            ...base,
            id: 'event',
            kind: 'event',
            description: 'Own event',
            dateLabel: '3º dia do inverno',
          },
        ],
      });
    }
    await exportManuscript({
      book,
      scope: 'book',
      format: 'json',
      currentChapter: version === 1 ? { ...chapter, id: 'removed-open-chapter' } : undefined,
      currentContent: '',
    });
    const blob = vi.mocked(downloadExport).mock.calls.at(-1)![0],
      bytes = new Uint8Array(await blob.arrayBuffer());
    const source = {
      size: bytes.length,
      read: (offset: number, length: number) =>
        Promise.resolve(bytes.slice(offset, offset + length)),
    };
    const report = await inspectBookLegacyContent(source, { index: indexFixture(), hash });
    expect(report.source.version).toBe(version);
    expect(report.validation).toBe('legacy-content-only');
    expect(report.source.availability.history).toBe('not-recorded');
    expect(report.source.availability.cover).toBe('url-only');
    expect(report.totals.chapters).toBe(version === 1 ? 2 : 1);
    expect(report.totals.resources.lore).toBe(1);
    expect(report.source.ignoredGlobalEntries).toBe(version >= 2 ? 1 : 0);
    expect(JSON.stringify(report)).not.toContain('PRIVATE_TOKEN');
    expect(JSON.stringify(report)).not.toContain('GLOBAL BODY');
    if (version >= 5) {
      expect(report.warnings.missingPersonas).toBe(1);
      expect(report.legacyWarnings.resolvedLabelsIgnored).toBe(1);
    }
  },
);
